#!/usr/bin/env node
/* HoopaDex — regulation change generator
 * Run: node build/generate-regulations.js
 *
 * Reads the regulation registry out of app/index.html — the same one the application filters by —
 * computes the set difference between each pair of regulations, and writes:
 *
 *   data/regulations.json   the machine-readable record, one entry per transition
 *   docs/REGULATIONS.md     the human-readable article
 *
 * The point is that neither artefact is written by hand. The app's Regulation Changes page derives
 * the same diff at runtime from the same registry, so the article, the page and the Pokédex filter
 * cannot disagree. Adding a regulation to CHAMPIONS_REGS is the only edit; running this regenerates
 * everything downstream.
 *
 * Species names come from PokéAPI once and are cached in data/species-names.json, so a rerun works
 * offline and produces byte-identical output.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const APP = path.join(ROOT, 'app', 'index.html');
const DATA_DIR = path.join(ROOT, 'data');
const DOCS_DIR = path.join(ROOT, 'docs');
const NAME_CACHE = path.join(DATA_DIR, 'species-names.json');

// --- pull the registry out of the shipped app -----------------------------------------
function readRegistry() {
  const lines = fs.readFileSync(APP, 'utf8').split(/\r?\n/);
  const start = lines.findIndex(l => l.startsWith('const CHAMPIONS_IDS_MA='));
  const end = lines.findIndex((l, i) => i > start && l.startsWith('const LATEST_REG='));
  if (start < 0 || end < 0) throw new Error('could not locate CHAMPIONS_REGS in app/index.html');
  return eval(lines.slice(start, end).join('\n') + '\n;({CHAMPIONS_REGS})').CHAMPIONS_REGS;
}

function diffs(regs) {
  const out = [];
  for (let i = 0; i < regs.length - 1; i++) {
    const to = regs[i], from = regs[i + 1];
    const a = from.ids(), b = to.ids();
    out.push({
      from: from.label, fromKey: from.key,
      to: to.label, toKey: to.key,
      previousSize: a.size, size: b.size,
      added: [...b].filter(id => !a.has(id)).sort((x, y) => x - y),
      removed: [...a].filter(id => !b.has(id)).sort((x, y) => x - y),
    });
  }
  return out;
}

// --- species names, fetched once then cached ------------------------------------------
async function speciesNames(ids) {
  let cache = {};
  if (fs.existsSync(NAME_CACHE)) cache = JSON.parse(fs.readFileSync(NAME_CACHE, 'utf8'));
  const missing = ids.filter(id => !cache[id]);
  if (missing.length) {
    if (typeof fetch !== 'function') throw new Error('need fetch (node 18+) to populate the name cache');
    process.stderr.write(`fetching ${missing.length} species name(s) from PokeAPI\n`);
    for (const id of missing) {
      const r = await fetch('https://pokeapi.co/api/v2/pokemon-species/' + id);
      if (!r.ok) { cache[id] = '#' + String(id).padStart(4, '0'); continue; }
      const d = await r.json();
      const en = (d.names || []).find(n => n.language.name === 'en');
      cache[id] = en ? en.name : d.name;
    }
    fs.mkdirSync(DATA_DIR, { recursive: true });
    fs.writeFileSync(NAME_CACHE, JSON.stringify(cache, null, 1) + '\n');
  }
  return cache;
}

(async () => {
  const regs = readRegistry();
  const list = diffs(regs);
  const everyId = [...new Set(list.flatMap(d => [...d.added, ...d.removed]))].sort((a, b) => a - b);
  const names = await speciesNames(everyId);
  const nameOf = id => names[id] || ('#' + String(id).padStart(4, '0'));

  // --- machine-readable ---------------------------------------------------------------
  const json = {
    note: 'Generated by build/generate-regulations.js from the registry in app/index.html. Do not edit by hand.',
    regulations: regs.map(r => ({ key: r.key, label: r.label, size: r.ids().size })),
    transitions: list.map(d => ({
      ...d,
      added: d.added.map(id => ({ id, name: nameOf(id) })),
      removed: d.removed.map(id => ({ id, name: nameOf(id) })),
    })),
  };
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(path.join(DATA_DIR, 'regulations.json'), JSON.stringify(json, null, 2) + '\n');

  // --- the article --------------------------------------------------------------------
  const L = [];
  L.push('# Pokémon Champions — Regulation Changes', '');
  L.push('What changed between each Champions regulation, newest first.', '');
  L.push('**Generated, not written.** `build/generate-regulations.js` derives this by set difference');
  L.push('over the same roster the Pokédex filters by, so this file, the in-app Regulation Changes');
  L.push('page and the dex itself cannot disagree. Do not edit it by hand — add the regulation to');
  L.push('`CHAMPIONS_REGS` in `app/index.html` and rerun the generator.', '');
  L.push('| Regulation | Roster size |', '|---|---|');
  regs.forEach(r => L.push(`| ${r.label} | ${r.ids().size} |`));
  L.push('');
  if (!list.length) L.push('_Only one regulation is on record, so there is nothing to compare yet._');
  list.forEach(d => {
    const net = d.size - d.previousSize;
    L.push('---', '', `## ${d.from} → ${d.to}`, '');
    L.push(`${d.previousSize} → ${d.size} Pokémon (${net >= 0 ? '+' : ''}${net}).`, '');
    L.push(`### Added (${d.added.length})`, '');
    L.push(d.added.length
      ? d.added.map(id => `- #${String(id).padStart(4, '0')} ${nameOf(id)}`).join('\n')
      : '_None._');
    L.push('', `### Removed (${d.removed.length})`, '');
    L.push(d.removed.length
      ? d.removed.map(id => `- #${String(id).padStart(4, '0')} ${nameOf(id)}`).join('\n')
      : '_None._');
    L.push('');
  });
  fs.mkdirSync(DOCS_DIR, { recursive: true });
  fs.writeFileSync(path.join(DOCS_DIR, 'REGULATIONS.md'), L.join('\n'));

  console.log(`${regs.length} regulations, ${list.length} transition(s)`);
  list.forEach(d => console.log(`  ${d.from} -> ${d.to}: +${d.added.length} / -${d.removed.length}`));
  console.log('wrote data/regulations.json and docs/REGULATIONS.md');
})().catch(e => { console.error(e.message); process.exit(1); });

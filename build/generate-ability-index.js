#!/usr/bin/env node
/* HoopaDex — the Abilities tab's list, in one file
 * Run: node build/generate-ability-index.js          (fetch PokeAPI, write app/abilities-index.json)
 *      node build/generate-ability-index.js --check  (fetch again, exit 1 if the file is stale)
 *
 * Why this exists. Reported from the live site: "abilities takes forever to load". To draw the list,
 * the tab fetched every ability's full PokeAPI record, 375 requests and about 5 MB, most of it flavour
 * text in a dozen languages. What the list reads from each record is four fields: the name, the
 * generation it arrived in, the English short effect and who has it. That is about 106 KB.
 *
 * This script reads exactly those fields from exactly those records, the same REST endpoints the app
 * called, so the file is the app's own input written down, not a second source. The app loads it in
 * one request and falls back to the old per-ability fetch if it cannot (opened from disk, or a 404).
 *
 * Staleness is the cost. PokeAPI changes rarely and additively; --check re-fetches and compares, and
 * the file records when it was taken.
 *
 * Format, kept compact because every visitor downloads it:
 *   abilities: [[name, genRoman, shortEffect, [[pokemonName, pokemonId, isHidden(0|1), slot], ...]], ...]
 * in PokeAPI's own order, holders in PokeAPI's own order.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'app', 'abilities-index.json');
const API = 'https://pokeapi.co/api/v2/';
const ROMAN = { i: 'I', ii: 'II', iii: 'III', iv: 'IV', v: 'V', vi: 'VI', vii: 'VII', viii: 'VIII', ix: 'IX' };

async function getJson(url, tries = 4) {
  for (let t = 1; ; t++) {
    try {
      const r = await fetch(url);
      if (!r.ok) throw new Error('HTTP ' + r.status + ' ' + url);
      return await r.json();
    } catch (e) {
      if (t >= tries) throw e;
      await new Promise(res => setTimeout(res, 500 * t));
    }
  }
}

/* The same reduction renderAbilitiesTab makes from a full record. Kept line-for-line equivalent so the
   file and the fallback path cannot describe an ability differently. */
function reduce(ab) {
  const en = (ab.effect_entries || []).find(e => e.language.name === 'en');
  const flav = (ab.flavor_text_entries || []).filter(e => e.language.name === 'en').pop();
  const desc = (en && en.short_effect) || (flav && flav.flavor_text) || '';
  const g = ab.generation && ab.generation.name ? ab.generation.name.replace('generation-', '') : '';
  const gen = ROMAN[g] || (g ? g.toUpperCase() : '?');
  const holders = (ab.pokemon || []).map(p => [
    p.pokemon.name, +p.pokemon.url.split('/').filter(Boolean).pop(), p.is_hidden ? 1 : 0, p.slot]);
  return [ab.name, gen, desc, holders];
}

async function build() {
  const idx = await getJson(API + 'ability?limit=400');
  if (idx.count > idx.results.length) throw new Error('PokeAPI has ' + idx.count + ' abilities; raise the limit (the app uses 400 too)');
  const out = new Array(idx.results.length);
  let next = 0;
  await Promise.all(Array.from({ length: 24 }, async () => {
    while (next < idx.results.length) {
      const i = next++;
      out[i] = reduce(await getJson(idx.results[i].url));
    }
  }));
  const seen = new Set();
  return out.filter(a => !seen.has(a[0]) && seen.add(a[0]));
}

(async () => {
  const check = process.argv.includes('--check');
  const abilities = await build();
  if (check) {
    const cur = JSON.parse(fs.readFileSync(OUT, 'utf8'));
    const same = JSON.stringify(cur.abilities) === JSON.stringify(abilities);
    console.log(same
      ? 'check: app/abilities-index.json matches PokeAPI (' + abilities.length + ' abilities, taken ' + cur.fetched + ')'
      : 'STALE: app/abilities-index.json differs from PokeAPI; rerun without --check');
    process.exit(same ? 0 : 1);
  }
  const doc = {
    about: 'Generated by build/generate-ability-index.js from PokeAPI. Do not edit by hand.',
    fetched: new Date().toISOString().slice(0, 10),
    count: abilities.length,
    abilities,
  };
  fs.writeFileSync(OUT, JSON.stringify(doc) + '\n');
  console.log('wrote app/abilities-index.json: ' + abilities.length + ' abilities, ' +
    (fs.statSync(OUT).size / 1024).toFixed(0) + ' KB');
})().catch(e => { console.error(e); process.exit(1); });

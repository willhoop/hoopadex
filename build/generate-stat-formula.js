#!/usr/bin/env node
/* HoopaDex — stat formula article generator
 * Run: node build/generate-stat-formula.js
 *
 * Writes docs/STAT-FORMULA.md.
 *
 * Every number in the article is computed by the SHIPPED functions, sliced out of app/index.html:
 * `bulkStat()` for the stat model and `SPEED_COLS` for the speed tiers. Nothing is typed out. The
 * point is the same as for the regulation article — if the app's model changes and this is rerun,
 * the article changes with it, and if it is not rerun the mismatch is a test failure rather than a
 * quietly wrong document.
 *
 * The article exists for one reason: HP uses a different constant from every other stat, and
 * applying the non-HP formula to HP is the mistake it is meant to prevent.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const APP = path.join(ROOT, 'app', 'index.html');
const OUT = path.join(ROOT, 'docs', 'STAT-FORMULA.md');

const lines = fs.readFileSync(APP, 'utf8').split(/\r?\n/);

function slice(startsWith, endsWith, what) {
  const a = lines.findIndex(l => l.startsWith(startsWith));
  const b = lines.findIndex((l, i) => i > a && l.startsWith(endsWith));
  if (a < 0 || b < 0) throw new Error('could not locate ' + what);
  return lines.slice(a, b).join('\n');
}

// Bound as `stat`, not `bulkStat`: a sloppy-mode eval hoists the sliced `function bulkStat` into
// this scope, so `const bulkStat` here would be a redeclaration. (`const SPEED_COLS` below is
// block-scoped inside its own eval and does not collide.)
const stat = eval(slice('function bulkStat(', 'function optimalBulkSplit(', 'bulkStat') +
  '\n;(bulkStat)');
const { SPEED_COLS } = eval(slice('const SPEED_COLS=[', 'let speedSortCol=', 'SPEED_COLS') +
  '\n;({SPEED_COLS})');

// Recover the two constants from the shipped function rather than restating them.
const HP_CONST = stat(0, 0, true, 1);
const OTHER_CONST = stat(0, 0, false, 1);
const MAX_SP = 32, BUDGET = 66;

if (HP_CONST === OTHER_CONST) {
  throw new Error('HP and non-HP constants are equal — the article has nothing to warn about, ' +
    'which means the model changed and this generator needs revisiting');
}

// Real Pokémon, real base stats. Kept small and recognisable; the numbers come from bulkStat.
const EXAMPLES = [
  { name: 'Blissey', hp: 255, atk: 10, def: 10, spa: 75, spd: 135, spe: 55 },
  { name: 'Jolteon', hp: 65, atk: 65, def: 60, spa: 110, spd: 95, spe: 130 },
  { name: 'Garchomp', hp: 108, atk: 130, def: 95, spa: 80, spd: 85, spe: 102 },
  { name: 'Shuckle', hp: 20, atk: 10, def: 230, spa: 10, spd: 230, spe: 5 },
];

const row = (label, cells) => '| ' + [label, ...cells].join(' | ') + ' |';

let md = `# Stat formula — Pokémon Champions

**Generated by \`build/generate-stat-formula.js\`. Do not edit by hand.**
Every number below is computed by the same functions the application ships; rerun the generator
after changing the model.

---

## The one thing to remember

**HP uses a different constant from every other stat.**

\`\`\`
HP          = base + ${HP_CONST} + SP
every other = floor((base + ${OTHER_CONST} + SP) × nature)
\`\`\`

Two differences, both easy to miss:

1. **The constant.** HP adds **${HP_CONST}**; everything else adds **${OTHER_CONST}**. That is a
   ${HP_CONST - OTHER_CONST}-point head start that HP has before a single Stat Point is spent.
2. **The nature.** A nature multiplies a normal stat. **It never touches HP.** There is no
   HP-boosting nature and no HP-hindering one.

Applying the non-HP formula to HP is the mistake this page exists to prevent. A base-100 Pokémon has
${stat(100, 0, true, 1)} HP and ${stat(100, 0, false, 1)} of any other stat at the same base
value — not the same number.

## The conditions these assume

Champions fixes everything the main games leave variable:

| | |
|---|---|
| Level | 50 |
| IVs | 31 in every stat, always |
| Stat Points | 0–${MAX_SP} per stat, ${BUDGET} total across all six |
| Each Stat Point | +1 to the stat, before the nature multiplier |

Because level and IVs are fixed, there is no level term and no IV term. That is the whole reason the
formula collapses to "base + a constant".

## Order of operations

\`\`\`
1. start from the base stat
2. add the constant  (${HP_CONST} for HP, ${OTHER_CONST} otherwise)
3. add the Stat Points
4. multiply by the nature   — non-HP stats only
5. floor
\`\`\`

Step 4 before step 5 matters. The nature multiplies the **whole** total, not just the Stat Points,
and the result is floored — so a Stat Point does not reliably buy one point of stat:

| Stat Points | neutral | boosting (×1.1) | hindering (×0.9) |
|---|---|---|---|
${[0, 1, 2, 3, 4].map(sp => row(sp, [
  stat(100, sp, false, 1), stat(100, sp, false, 1.1), stat(100, sp, false, 0.9),
])).join('\n')}

Read the hindering column: the first Stat Point buys **nothing**. Read the boosting column across
its full range and you will find steps of 2. This is why "add to whichever stat is lower" is exactly
optimal on a neutral nature and slightly off with one — see \`docs/BACKLOG.md\` item 22.

## Worked examples

At 0 Stat Points and a neutral nature:

| Pokémon | base HP → HP | base Def → Def | base Spe → Spe |
|---|---|---|---|
${EXAMPLES.map(p => row(p.name, [
  `${p.hp} → **${stat(p.hp, 0, true, 1)}**`,
  `${p.def} → ${stat(p.def, 0, false, 1)}`,
  `${p.spe} → ${stat(p.spe, 0, false, 1)}`,
])).join('\n')}

Blissey is the clearest illustration: base HP ${EXAMPLES[0].hp} becomes
**${stat(255, 0, true, 1)}**, while base Defence ${EXAMPLES[0].def} becomes only
${stat(10, 0, false, 1)}. Using the non-HP constant for HP would have said
${255 + OTHER_CONST} — out by ${HP_CONST - OTHER_CONST}.

## Maximum values

With all ${MAX_SP} Stat Points in one stat:

| | neutral | boosting |
|---|---|---|
| HP from base 100 | ${stat(100, MAX_SP, true, 1)} | ${stat(100, MAX_SP, true, 1)} (natures do not apply) |
| Other from base 100 | ${stat(100, MAX_SP, false, 1)} | ${stat(100, MAX_SP, false, 1.1)} |

The ${BUDGET}-point budget is shared across all six stats, so at most two stats can be taken to
${MAX_SP} (${2 * MAX_SP} points), leaving ${BUDGET - 2 * MAX_SP} over.

## Speed tiers use the same model

The Speed Tiers table under **Other** is this formula and nothing else. Its columns, taken from the
shipped definitions:

| Column | Meaning | Base 100 | Base 130 |
|---|---|---|---|
${SPEED_COLS.map(c => row(c.label, [c.hint, c.f(100), c.f(130)])).join('\n')}

Base 130 is Jolteon, which is the row this model was originally checked against.

---

*Sources: the application's own \`bulkStat()\` and \`SPEED_COLS\`, sliced from \`app/index.html\` at
generation time.*
`;

fs.writeFileSync(OUT, md);
console.log('wrote ' + path.relative(ROOT, OUT));
console.log('  HP constant:        ' + HP_CONST);
console.log('  other-stat constant:' + OTHER_CONST);
console.log('  speed columns:      ' + SPEED_COLS.map(c => c.label).join(', '));
console.log('  Jolteon (base 130): ' + SPEED_COLS.map(c => c.f(130)).join(' / '));
